-- Calculate Job Readiness Score
CREATE OR REPLACE FUNCTION calculate_job_readiness_score(
  p_learner_id UUID,
  p_job_role_id UUID
) RETURNS INTEGER AS $$
DECLARE
  v_score INTEGER := 0;
  v_required_skills INTEGER;
  v_acquired_skills INTEGER;
BEGIN
  -- Count required skills for target job role
  SELECT COUNT(*) INTO v_required_skills
  FROM job_role_skills
  WHERE job_role_id = p_job_role_id AND importance = 'required';
  
  -- Count acquired skills from learner's progress
  -- This is a simplified version - actual implementation would check skill proficiency
  SELECT COUNT(DISTINCT skill_id) INTO v_acquired_skills
  FROM course_skills cs
  JOIN path_steps ps ON cs.course_id = ps.course_id
  JOIN step_progress sp ON ps.id = sp.path_step_id
  WHERE sp.learner_id = p_learner_id 
    AND sp.status = 'completed'
    AND cs.skill_id IN (
      SELECT skill_id FROM job_role_skills 
      WHERE job_role_id = p_job_role_id AND importance = 'required'
    );
  
  -- Calculate percentage
  IF v_required_skills > 0 THEN
    v_score := (v_acquired_skills * 100) / v_required_skills;
  END IF;
  
  RETURN LEAST(v_score, 100); -- Cap at 100
END;
$$ LANGUAGE plpgsql;

-- Update learner metrics (called after progress updates)
CREATE OR REPLACE FUNCTION update_learner_metrics(p_learner_id UUID)
RETURNS VOID AS $$
DECLARE
  v_learning_path_id UUID;
  v_job_role_id UUID;
  v_jrs INTEGER;
  v_sav DECIMAL(5,2);
  v_pcr DECIMAL(5,2);
BEGIN
  -- Get active learning path
  SELECT id, job_role_id INTO v_learning_path_id, v_job_role_id
  FROM learning_paths
  WHERE learner_id = p_learner_id AND status = 'active'
  LIMIT 1;
  
  IF v_learning_path_id IS NOT NULL THEN
    -- Calculate JRS
    v_jrs := calculate_job_readiness_score(p_learner_id, v_job_role_id);
    
    -- Calculate SAV (skills acquired per week)
    SELECT COALESCE(
      (COUNT(DISTINCT cs.skill_id) / 
       NULLIF(EXTRACT(WEEK FROM AGE(NOW(), MIN(sp.started_at))), 0)),
      0
    ) INTO v_sav
    FROM step_progress sp
    JOIN path_steps ps ON sp.path_step_id = ps.id
    JOIN course_skills cs ON ps.course_id = cs.course_id
    WHERE sp.learner_id = p_learner_id 
      AND sp.status = 'completed'
      AND sp.started_at IS NOT NULL;
    
    -- Calculate PCR
    SELECT COALESCE(progress_percentage, 0) INTO v_pcr
    FROM path_progress
    WHERE learner_id = p_learner_id 
      AND learning_path_id = v_learning_path_id;
    
    -- Insert or update metrics
    INSERT INTO learner_metrics (
      learner_id,
      learning_path_id,
      job_readiness_score,
      skill_acquisition_velocity,
      path_completion_rate,
      calculated_at
    ) VALUES (
      p_learner_id,
      v_learning_path_id,
      v_jrs,
      v_sav,
      v_pcr,
      NOW()
    )
    ON CONFLICT (learner_id, learning_path_id) 
    DO UPDATE SET
      job_readiness_score = v_jrs,
      skill_acquisition_velocity = v_sav,
      path_completion_rate = v_pcr,
      calculated_at = NOW();
  END IF;
END;
$$ LANGUAGE plpgsql;

