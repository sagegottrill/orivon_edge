-- AI PATHFINDING PLATFORM DATABASE SCHEMA
-- Comprehensive schema for personalized learning path system

-- ============================================
-- USER PROFILES & AUTHENTICATION
-- ============================================

-- Extended user profiles with career goals and preferences
CREATE TABLE IF NOT EXISTS learner_profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  full_name TEXT NOT NULL,
  phone TEXT,
  location TEXT,
  
  -- Career Information
  current_role TEXT,
  target_role TEXT NOT NULL,
  experience_level TEXT CHECK (experience_level IN ('beginner', 'intermediate', 'advanced')),
  industry_preference TEXT[],
  
  -- Learning Preferences
  learning_style TEXT CHECK (learning_style IN ('visual', 'auditory', 'reading', 'kinesthetic', 'mixed')),
  weekly_hours_available INTEGER DEFAULT 10,
  preferred_learning_time TEXT CHECK (preferred_learning_time IN ('morning', 'afternoon', 'evening', 'flexible')),
  
  -- Background
  education_level TEXT,
  previous_skills TEXT[],
  languages TEXT[] DEFAULT ARRAY['English'],
  
  -- Profile Status
  onboarding_completed BOOLEAN DEFAULT FALSE,
  profile_completed_at TIMESTAMP WITH TIME ZONE,
  
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Initial skill assessment results
CREATE TABLE IF NOT EXISTS skill_assessments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  learner_id UUID REFERENCES learner_profiles(id) ON DELETE CASCADE,
  
  assessment_type TEXT CHECK (assessment_type IN ('initial', 'progress', 'final')),
  
  -- Technical Skills (0-100 score)
  programming_fundamentals INTEGER DEFAULT 0,
  web_development INTEGER DEFAULT 0,
  data_analysis INTEGER DEFAULT 0,
  mobile_development INTEGER DEFAULT 0,
  cloud_computing INTEGER DEFAULT 0,
  ai_ml INTEGER DEFAULT 0,
  
  -- Soft Skills (0-100 score)
  problem_solving INTEGER DEFAULT 0,
  communication INTEGER DEFAULT 0,
  teamwork INTEGER DEFAULT 0,
  adaptability INTEGER DEFAULT 0,
  
  -- Overall Score
  overall_score INTEGER GENERATED ALWAYS AS (
    (programming_fundamentals + web_development + data_analysis + 
     mobile_development + cloud_computing + ai_ml + 
     problem_solving + communication + teamwork + adaptability) / 10
  ) STORED,
  
  completed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- ============================================
-- SKILLS & COMPETENCIES
-- ============================================

-- Master list of skills/competencies
CREATE TABLE IF NOT EXISTS skills (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL, -- 'technical', 'soft', 'domain'
  subcategory TEXT,
  description TEXT,
  
  -- Market Data
  demand_score INTEGER DEFAULT 50, -- 0-100, how in-demand this skill is
  average_salary_impact DECIMAL(10,2), -- naira impact on salary
  
  -- Learning Metadata
  difficulty_level TEXT CHECK (difficulty_level IN ('beginner', 'intermediate', 'advanced', 'expert')),
  estimated_hours INTEGER, -- hours to achieve proficiency
  
  prerequisites UUID[], -- array of skill IDs that should be learned first
  
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Job roles and their required skills
CREATE TABLE IF NOT EXISTS job_roles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  title TEXT NOT NULL,
  description TEXT,
  category TEXT, -- 'software', 'data', 'design', 'product', etc.
  
  -- Market Data
  average_salary_min DECIMAL(12,2),
  average_salary_max DECIMAL(12,2),
  job_openings_count INTEGER DEFAULT 0,
  growth_rate DECIMAL(5,2), -- percentage
  
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Skills required for each job role
CREATE TABLE IF NOT EXISTS job_role_skills (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  job_role_id UUID REFERENCES job_roles(id) ON DELETE CASCADE,
  skill_id UUID REFERENCES skills(id) ON DELETE CASCADE,
  
  importance TEXT CHECK (importance IN ('required', 'preferred', 'nice-to-have')),
  proficiency_level TEXT CHECK (proficiency_level IN ('basic', 'intermediate', 'advanced', 'expert')),
  
  UNIQUE(job_role_id, skill_id)
);

